/**
 * 🌍 ด่านกันภาษาต่างด้าวหลุดเข้าคำอ่าน — รวมภาษาที่ใช้ "อักษรละตินเหมือนอังกฤษ"
 * ===========================================================================
 *
 * เคสจริงที่ผู้ใช้ถ่ายหน้าจอมาให้ดู:
 *
 *   "ในบริบทที่ você เบื่อชีวิต ไพ่ใบนี้กำลังบอกเป็นนัยว่า..."
 *
 * `você` = "คุณ" ในภาษาโปรตุเกส · ด่านเดิม (`FOREIGN_SCRIPT_REGEX`) ดูเฉพาะอักษร
 * **ที่ไม่ใช่ละติน** — จีน ญี่ปุ่น เกาหลี รัสเซีย อาหรับ ฮินดี ฮีบรู — จึงนับได้ **0 ตัว**
 * ไม่มีอะไรทำงานเลย ทั้งที่โมเดลหลายภาษาอย่าง Qwen หลุดเป็นภาษากลุ่มละตินง่ายกว่าจีน
 *
 * ## สิ่งที่ด่านนี้บังคับ
 *
 * 1. ภาษาละตินต่างด้าวต้องถูกจับได้ (โปรตุเกส สเปน ฝรั่งเศส เยอรมัน เวียดนาม อินโดนีเซีย)
 * 2. **ภาษาอังกฤษต้องไม่ถูกแตะแม้แต่ตัวเดียว** — ชื่อไพ่ 78 ใบและหน้า `/en` ทั้งชุด
 *    เป็นภาษาอังกฤษโดยชอบธรรม ด่านที่จับอังกฤษด้วยคือด่านที่พังทั้งเว็บ
 * 3. ตัดคำต้องตัด **ทั้งคำ** ห้ามเหลือเศษอย่าง `voc` หรือ `no`
 * 4. ของเดิม (จีน/ญี่ปุ่น) ต้องยังทำงานเหมือนเดิม
 *
 * ⚠️ ข้อจำกัดที่รู้ตัว: คำต่างด้าวที่ **ไม่มีเครื่องหมายกำกับและไม่อยู่ในคลังคำ**
 * (เช่น `necesita` ของสเปน · `harus` ของอินโดนีเซีย) ยังหลุดได้
 * เส้นแบ่งนี้เลือกไว้โดยตั้งใจ — จะจับให้ครบต้องเดาว่าคำละตินคำไหนไม่ใช่อังกฤษ
 * ซึ่งเสี่ยงไปแตะชื่อไพ่และคำอ่านอังกฤษจริง · ถ้าเจอคำใหม่หลุดมา ให้เติมลง
 * `LATIN_LEAK_MAP` แล้วเพิ่มบรรทัดในคลังทดสอบข้างล่าง
 *
 * รันเดี่ยว: npx tsx scripts/qa/test-foreign-leak.ts
 */

import {
  countForeignCharacters,
  hasForeignScript,
  sanitizeTarotText,
} from "../../src/lib/ai/language";

let failed = 0;
const check = (label: string, ok: boolean, detail?: string) => {
  console.log(`  ${ok ? "✅" : "❌"} ${label}`);
  if (!ok) {
    failed += 1;
    if (detail) console.log(`      ${detail}`);
  }
};

console.log("\n=======================================================");
console.log("🌍 FOREIGN LANGUAGE LEAK GUARD — รวมภาษาอักษรละติน");
console.log("=======================================================\n");

// ── 1. ต้องจับได้ ────────────────────────────────────────────────────────────
/** [ข้อความ, ภาษา, คำต่างด้าวที่ต้องหายไปจากผลลัพธ์] */
const MUST_CATCH: Array<[string, string, string]> = [
  ["ในบริบทที่ você เบื่อชีวิต ไพ่ใบนี้กำลังบอกเป็นนัย", "โปรตุเกส (เคสจริงจากผู้ใช้)", "você"],
  ["ไพ่ใบนี้บอกว่า não ควรรีบตัดสินใจตอนนี้", "โปรตุเกส", "não"],
  ["สิ่งที่ usted ต้องระวังคือความใจร้อน", "สเปน", "usted"],
  ["ความรักของคุณ está ในช่วงเปลี่ยนผ่าน", "สเปน", "está"],
  ["ไพ่บอกว่า vous ควรฟังเสียงหัวใจตัวเอง", "ฝรั่งเศส", "vous"],
  ["ความรักของคุณ compliqué ในตอนนี้", "ฝรั่งเศส", "compliqué"],
  ["ช่วงนี้ müssen ระวังเรื่องการเงินให้มาก", "เยอรมัน", "müssen"],
  ["ไพ่บอกว่า bạn ควรพักผ่อนให้มากกว่านี้", "เวียดนาม", "bạn"],
  ["เรื่องนี้ anda ต้องตัดสินใจด้วยตัวเอง", "อินโดนีเซีย", "anda"],
  ["สิ่งที่ kamu กำลังมองหาอยู่ใกล้กว่าที่คิด", "อินโดนีเซีย", "kamu"],
  ["ไพ่บอกว่า porque ทุกอย่างมีเหตุผลของมัน", "สเปน (คำเชื่อม)", "porque"],
  ["ขอให้โชคดี obrigado ที่ไว้ใจแม่หมอ", "โปรตุเกส (คำขอบคุณ)", "obrigado"],
  ["ไพ่ 但是 บอกว่าให้รออีกสักพัก", "จีน (ของเดิมต้องยังทำงาน)", "但是"],
  ["ไพ่ そして บอกว่าให้รออีกสักพัก", "ญี่ปุ่น (ของเดิมต้องยังทำงาน)", "そして"],
];

console.log("── 1. ภาษาต่างด้าวต้องถูกจับและถูกเอาออก ──");
for (const [text, lang, leak] of MUST_CATCH) {
  const detected = hasForeignScript(text);
  const cleaned = sanitizeTarotText(text);
  const gone = !cleaned.includes(leak);
  check(`${lang.padEnd(34)} "${leak}"`, detected && gone,
    !detected ? "ตรวจไม่พบว่ามีภาษาต่างด้าว" : `ยังเหลือคำว่า "${leak}" ในผลลัพธ์: ${cleaned}`);
}

// ── 2. ห้ามแตะภาษาอังกฤษเด็ดขาด ──────────────────────────────────────────────
const MUST_NOT_TOUCH: Array<[string, string]> = [
  ["ไพ่ The Lovers หมายถึงความสัมพันธ์ที่กำลังเบ่งบาน", "ชื่อไพ่ในประโยคไทย"],
  ["The Wheel of Fortune บอกว่าโชคชะตากำลังหมุน", "ชื่อไพ่ขึ้นต้นประโยค"],
  ["ไพ่ Ten of Swords กลับหัว แปลว่าความเจ็บปวดกำลังจะจบ", "ชื่อไพ่กลางประโยค"],
  ["This card suggests you should rest and reflect on what matters.", "คำอ่านอังกฤษเต็มประโยค (หน้า /en)"],
  ["The Hermit invites you to look inward before making any decision.", "คำอ่านอังกฤษเต็มประโยค"],
  ["Your energy is shifting — trust the process and be patient.", "คำอ่านอังกฤษมีขีดกลาง"],
  ["ลอง reflect ดูว่าสิ่งที่คุณต้องการจริง ๆ คืออะไร", "คำอังกฤษทับศัพท์ในประโยคไทย"],
  ["ดวงการงานเดือนนี้ดีมาก 100% เลยนะ", "ตัวเลขและเครื่องหมาย"],
];

console.log("\n── 2. ภาษาอังกฤษและชื่อไพ่ต้องไม่ถูกแตะเลย ──");
for (const [text, note] of MUST_NOT_TOUCH) {
  const weight = countForeignCharacters(text);
  const cleaned = sanitizeTarotText(text);
  // `polishThai` อาจปรับช่องไฟไม้ยมกได้ จึงเทียบแบบยุบช่องว่าง
  const same = cleaned.replace(/\s+/g, " ").trim() === text.replace(/\s+/g, " ").trim();
  check(`${note.padEnd(38)} น้ำหนัก ${weight}`, weight === 0 && same,
    weight !== 0 ? `นับเป็นต่างด้าว ${weight} ทั้งที่เป็นอังกฤษ` : `ข้อความถูกแก้: "${cleaned}"`);
}

// ── 3. ตัดต้องตัดทั้งคำ ห้ามเหลือเศษ ─────────────────────────────────────────
console.log("\n── 3. ตัดทั้งคำ ห้ามเหลือคำพิการ ──");
const FRAGMENTS: Array<[string, string[]]> = [
  ["ในบริบทที่ você เบื่อชีวิต", ["voc", "voce"]],
  ["ไพ่บอกว่า não ควรรีบ", ["no ", "na "]],
  ["ความรักของคุณ compliqué ตอนนี้", ["compliqu"]],
];
for (const [text, bad] of FRAGMENTS) {
  const cleaned = sanitizeTarotText(text);
  const found = bad.filter((b) => cleaned.includes(b));
  check(`"${text.slice(0, 30)}…" ไม่เหลือเศษคำ`, found.length === 0,
    `พบเศษ: ${found.join(", ")} ในผลลัพธ์ "${cleaned}"`);
}

// ── 4. ประโยคต่างด้าวเต็มย่อหน้าต้องถึงเกณฑ์ตัดวงจร ─────────────────────────
console.log("\n── 4. หลุดทั้งประโยคต้องถึงเกณฑ์สลับโมเดล (14 ตัว) ──");
const FULL_SENTENCE = "Você está passando por um momento de transformação profunda";
const w = countForeignCharacters(FULL_SENTENCE);
check(`ประโยคโปรตุเกสเต็ม ๆ ได้น้ำหนัก ${w} (ต้อง >= 14)`, w >= 14,
  "ถ้าไม่ถึงเกณฑ์ ตัวตัดวงจรจะไม่สลับโมเดล ผู้ใช้จะได้คำอ่านภาษาโปรตุเกสทั้งย่อหน้า");

const SINGLE_WORD = "ในบริบทที่ você เบื่อชีวิต ไพ่ใบนี้กำลังบอกเป็นนัยว่าคุณกำลังเหนื่อย";
const w2 = countForeignCharacters(SINGLE_WORD);
check(`คำเดี่ยวได้น้ำหนัก ${w2} (ต้อง < 14 เพื่อให้แก้เงียบ ๆ ไม่ failover)`, w2 > 0 && w2 < 14,
  "คำเดียวไม่ควรทิ้งคำอ่านทั้งชุดแล้วเรียกโมเดลใหม่ — เสียเวลาที่ผู้ใช้นั่งรอโดยไม่จำเป็น");

// ── สรุป ────────────────────────────────────────────────────────────────────
const total = MUST_CATCH.length + MUST_NOT_TOUCH.length + FRAGMENTS.length + 2;
if (failed > 0) {
  console.log(`\n❌ ไม่ผ่าน ${failed} จาก ${total} ข้อ\n`);
  process.exit(1);
}
console.log(`\n✨ ผ่านครบ ${total} ข้อ — ภาษาต่างด้าวถูกจับ ภาษาอังกฤษปลอดภัย\n`);
