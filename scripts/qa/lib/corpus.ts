/**
 * 🧮 ยืนยันว่า "คลังที่ด่านนี้จะตรวจ" ไม่ว่างเปล่า
 * ---------------------------------------------------------------------------
 * ## ทำไมต้องมี (บทเรียน R-05)
 *
 * **"สแกนศูนย์ไฟล์" กับ "ไม่พบข้อผิดพลาด" ให้ผลลัพธ์เหมือนกันทุกประการ**
 *
 * ด่านส่วนใหญ่ในโฟลเดอร์นี้เขียนแบบ "วนทุกไฟล์แล้วบ่นเมื่อเจอของผิด" ซึ่งถูกต้อง
 * จนกระทั่งวันที่คลังกลายเป็นอาเรย์ว่าง — เปลี่ยนชื่อโฟลเดอร์ · ย้ายไฟล์ · CI ยังไม่ build ·
 * `walk()` ชี้ผิดที่ — แล้วด่านนั้นจะรายงาน ✅ ผ่าน ทั้งที่ไม่ได้ตรวจอะไรเลยสักบรรทัด
 *
 * รอบตรวจ 2026-09-17 พบ **19 จาก 22 ด่าน** ที่วนอ่านคลังไฟล์โดยไม่เคยตรวจว่าคลังว่างหรือไม่
 *
 * ## วิธีใช้
 *
 * ```ts
 * const pages = renderedRouteMap();
 * assertNonEmptyCorpus("หน้าที่เรนเดอร์แล้ว", pages, "รัน `npm run build` ก่อน");
 * ```
 *
 * ล้มทันทีด้วย `process.exit(1)` เพราะการตรวจต่อจากคลังว่างไม่มีความหมาย
 * และการปล่อยให้ผ่านคือการโกหกผู้ตรวจ
 *
 * ⚠️ ด่าน `scripts/qa/test-gate-integrity.ts` บังคับให้ทุกด่านที่อ่านคลังไฟล์เรียกฟังก์ชันนี้
 */
export function assertNonEmptyCorpus(
  label: string,
  corpus: { length: number } | Map<unknown, unknown> | Set<unknown>,
  hint = "",
): void {
  const size =
    corpus instanceof Map || corpus instanceof Set
      ? corpus.size
      : (corpus as { length: number }).length;

  if (size > 0) {
    console.log(`   📂 คลังที่จะตรวจ: ${label} — ${size} รายการ`);
    return;
  }

  console.error(
    `\n❌ คลัง "${label}" ว่างเปล่า — ด่านนี้จะรายงานผ่านโดยไม่ได้ตรวจอะไรเลย\n` +
      `   "สแกนศูนย์ไฟล์" กับ "ไม่พบข้อผิดพลาด" หน้าตาเหมือนกันทุกประการ จึงถือว่าตกทันที` +
      (hint ? `\n   ➔ ${hint}` : ""),
  );
  process.exit(1);
}
