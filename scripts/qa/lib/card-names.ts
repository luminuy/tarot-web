import type { Suit } from "../../../src/data/cards/types";

export const SUIT_TH: Record<Suit, string> = {
  wands: "ไม้เท้า",
  cups: "ถ้วย",
  swords: "ดาบ",
  pentacles: "เหรียญ",
};

/** ลำดับ 1–14 ตามเลข `number` ของไพ่ (11 = Page · 12 = Knight · 13 = Queen · 14 = King) */
export const RANK_TH = ["เอซ", "สอง", "สาม", "สี่", "ห้า", "หก", "เจ็ด", "แปด", "เก้า", "สิบ", "เพจ", "อัศวิน", "ราชินี", "ราชา"] as const;

export function canonicalMinorNameTh(suit: Suit, number: number): string {
  return `${RANK_TH[number - 1]}แห่ง${SUIT_TH[suit]}`;
}

const SUITS = Object.values(SUIT_TH).join("|");
const RANKS = [...RANK_TH, "บริวาร", "เด็กหนุ่ม", "เด็กรับใช้"].join("|");

/**
 * ชื่อแบบเก่า/แบบเพี้ยนที่ห้ามใช้ในข้อความภาษาไทย
 * - ลำดับติดชุดโดยไม่มี "แห่ง" (สองถ้วย · ราชินีถ้วย · เอซไม้เท้า)
 * - ชื่อ Page แบบเดิม (บริวารแห่งดาบ · เด็กหนุ่มแห่งเหรียญ)
 * - ชุดตามด้วยเลข (ไม้เท้า 8) — ยกเว้นเลขที่ตามด้วยลักษณนาม ซึ่งเป็นคำบรรยายภาพ ("ไม้เท้า 8 ท่อน")
 *
 * ⚠️ ห้ามใช้สแกนไฟล์คำบรรยายภาพ (`visual-lore.ts` · `gaze.ts` · ตัวอย่างใน prompt) —
 *    ภาษาไทยนับของด้วย "สองเหรียญ" / "ระหว่างสองถ้วย" ได้ตามปกติ
 */
export const NON_CANONICAL_MINOR_NAME_TH = new RegExp(
  `(?:${RANKS})(?:${SUITS})|(?:บริวาร|เด็กหนุ่ม|เด็กรับใช้)แห่ง(?:${SUITS})|(?:${SUITS}) ?(?:10|[1-9])(?!\\d|\\s*(?:ใบ|เล่ม|ท่อน|อัน|เหรียญ|ด้าม))`,
  "g",
);
