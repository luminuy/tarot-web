/**
 * ชั้นความปลอดภัยของคำถาม
 * -------------------------------------------------
 * เว็บดูดวงคือที่ที่คนพิมพ์เรื่องที่ไม่กล้าบอกใคร ส่วนหนึ่งจะมาในวันที่แย่ที่สุดของเขา
 * นี่ไม่ใช่ฟีเจอร์เสริม แต่เป็นสิ่งที่ต้องมีตั้งแต่วันแรกที่เปิดเว็บ
 *
 * ระบบมีสองชั้น:
 *   1. ตัวกรองคำ (ไฟล์นี้) — เร็ว ไม่เสียค่า token และทำงานก่อนเรียกโมเดล
 *   2. คำสั่งใน system prompt — กันกรณีที่ตัวกรองคำจับไม่ได้
 * ทั้งสองชั้นต้องมี ชั้นเดียวไม่พอ
 */

export type SafetyFlag = "crisis" | "medical" | "legal" | "gambling" | "third_party" | "none";

export interface SafetyVerdict {
  flag: SafetyFlag;
  /** true = ห้ามเปิดไพ่ ให้แสดงข้อความช่วยเหลือแทน */
  block: boolean;
  /** ข้อความที่แสดงต่อผู้ใช้เมื่อ block */
  message?: string;
  /** คำเตือนที่ต้องแทรกเข้า prompt เมื่อไม่ block แต่ต้องระวัง */
  promptGuard?: string;
}

/**
 * สัญญาณการทำร้ายตัวเอง
 * ระวังภาษาพูดไทย: "จะตาย" เป็นคำขยายที่ใช้ทั่วไป ("เหนื่อยจะตาย" "หิวจะตาย")
 * จึงห้ามจับคำว่า "ตาย" ลอย ๆ ต้องจับเฉพาะรูปที่สื่อเจตนาจริง
 */
const CRISIS_PATTERNS: RegExp[] = [
  /ฆ่าตัวตาย/,
  /อยาก(จะ)?ตาย/,
  /ไม่อยาก(มีชีวิต|อยู่ต่อ|อยู่แล้ว|ตื่นขึ้นมา)/,
  /จบชีวิต|จบ ๆ ไปเลย|ปลิดชีพ/,
  /ทำร้ายตัวเอง|ทำร้ายร่างกายตัวเอง/,
  /กรีด(แขน|ข้อมือ|ตัวเอง)/,
  /กินยา(ฆ่าตัวตาย|เกินขนาด|ทั้งขวด)/,
  /(แขวนคอ|โดดตึก|โดดสะพาน|รมควัน)/,
  /หายไปจากโลกนี้|ไม่มีใครสนใจถ้าฉันหายไป|โลกนี้ไม่มีที่ให้ฉัน/,
  /อยู่ไปก็เป็นภาระ/,
  /\bsuicide\b|\bkill myself\b|\bend my life\b|\bself.?harm\b/i,
];

const MEDICAL_PATTERNS: RegExp[] = [
  /(เป็น|ป่วย|ติด)(มะเร็ง|เอดส์|เบาหวาน|ซึมเศร้า|ไบโพลาร์|วัณโรค)/,
  /ผล(ตรวจ|เลือด|แล็บ)/,
  /(ต้อง|ควร)(ผ่าตัด|กินยา|หยุดยา|เปลี่ยนยา)/,
  /ท้อง(อยู่)?(ไหม|หรือเปล่า|รึเปล่า|รึยัง|หรือยัง)|ตั้งครรภ์|แท้ง/,
  /หายไหม|จะหายเมื่อไหร่|จะรอดไหม/,
];

const LEGAL_PATTERNS: RegExp[] = [
  /(คดี|ฟ้อง|ศาล|ทนาย|ตำรวจ|แจ้งความ|ติดคุก|ประกันตัว)/,
  /(หย่า|แบ่งสมบัติ|มรดก|พินัยกรรม)/,
];

const GAMBLING_PATTERNS: RegExp[] = [
  /(เลข|หวย|ล็อตเตอรี่|สลาก|ยี่กี|บาคาร่า|พนัน|บอล)(เด็ด|อะไร|ตัวไหน|งวดนี้|ออกอะไร)?/,
  /(เลขท้าย|สองตัว|สามตัว)/,
  /(หุ้น|คริปโต|เหรียญ|coin)(ตัวไหน|อะไร|ควรซื้อ|จะขึ้น|จะลง)/,
  /ควร(ซื้อ|ลงทุน|เทรด).*(หุ้น|คริปโต|ทอง|ที่ดิน)/,
];

/**
 * คำถามที่ล้วงข้อมูลบุคคลที่สาม เช่น "เขานอกใจกับใคร ชื่ออะไร" หรือ "มือที่สามชื่ออะไร"
 * ต้องครอบทั้งสองลำดับคำ เพราะภาษาพูดไทยสลับตำแหน่งประธาน/กริยาได้ทั้งสองแบบ
 */
const THIRD_PARTY_PATTERNS: RegExp[] = [
  /(ชื่อ|หน้าตา|ที่อยู่|เบอร์|ทำงานที่ไหน)(ของ)?(มือที่สาม|ชู้|คนที่เขาคุยด้วย)/,
  /(มือที่สาม|ชู้|คนที่เขาคุยด้วย)(ชื่อ|หน้าตา|ที่อยู่|เบอร์|ทำงานที่ไหน)/,
  /(ใคร|คนไหน)(เป็น)?(มือที่สาม|ชู้)/,
];

const CRISIS_MESSAGE = `ก่อนจะเปิดไพ่ ขอหยุดตรงนี้สักครู่นะ

สิ่งที่คุณเขียนมาทำให้เราเป็นห่วง และเรื่องแบบนี้ไม่ควรให้ไพ่เป็นคนตอบ — มันหนักเกินกว่าที่ไพ่จะรับไหว และคุณสมควรได้คุยกับคนจริง ๆ ที่ฟังคุณได้ทั้งหมด

**สายด่วนสุขภาพจิต 1323** โทรฟรี ตลอด 24 ชั่วโมง
**สมาคมสะมาริตันส์แห่งประเทศไทย** 02-713-6793 (เที่ยงวัน – ห้าทุ่ม)
ถ้ากำลังตกอยู่ในอันตรายทันที โทร **1669**

ถ้ายังไม่พร้อมโทรหาใคร ลองบอกคนที่อยู่ใกล้ที่สุดตอนนี้ว่าคุณกำลังไม่ไหว แค่ประโยคเดียวก็พอ

ไพ่จะยังอยู่ตรงนี้ กลับมาเปิดเมื่อไหร่ก็ได้ ตอนนี้ขอให้คุณได้รับการดูแลก่อน`;

function matchAny(patterns: RegExp[], text: string): boolean {
  return patterns.some((p) => p.test(text));
}

/**
 * ตรวจคำถามก่อนเปิดไพ่
 * ออกแบบให้ "ระแวงไว้ก่อน" ในกรณีสัญญาณวิกฤต —
 * การเตือนเกินจำเป็นสร้างความรำคาญ แต่การพลาดสักครั้งเดียวเสียหายกว่ามาก
 */
export function checkQuestion(rawQuestion: string): SafetyVerdict {
  const text = rawQuestion.normalize("NFC").trim();
  if (!text) return { flag: "none", block: false };

  if (matchAny(CRISIS_PATTERNS, text)) {
    return { flag: "crisis", block: true, message: CRISIS_MESSAGE };
  }

  if (matchAny(MEDICAL_PATTERNS, text)) {
    return {
      flag: "medical",
      block: false,
      promptGuard:
        "คำถามนี้พาดพิงเรื่องสุขภาพหรือร่างกาย ห้ามวินิจฉัย ห้ามทำนายว่าจะหายหรือไม่หาย ห้ามพูดถึงโรคเฉพาะเจาะจง ให้อ่านเฉพาะสภาพจิตใจ การดูแลตัวเอง และกำลังใจ พร้อมบอกอย่างอ่อนโยนว่าเรื่องร่างกายควรให้แพทย์เป็นคนตอบ",
    };
  }

  if (matchAny(LEGAL_PATTERNS, text)) {
    return {
      flag: "legal",
      block: false,
      promptGuard:
        "คำถามนี้พาดพิงเรื่องกฎหมายหรือคดีความ ห้ามทำนายผลคดี ห้ามให้คำแนะนำทางกฎหมาย ให้อ่านเฉพาะสภาพใจของผู้ถามและท่าทีที่ควรใช้รับมือ พร้อมแนะให้ปรึกษาผู้เชี่ยวชาญด้านกฎหมาย",
    };
  }

  if (matchAny(GAMBLING_PATTERNS, text)) {
    return {
      flag: "gambling",
      block: false,
      promptGuard:
        "คำถามนี้เกี่ยวกับตัวเลข การพนัน หรือการลงทุนเฉพาะเจาะจง ห้ามให้ตัวเลข ห้ามระบุสินทรัพย์ ห้ามบอกว่าจะได้หรือจะเสีย ให้ปฏิเสธส่วนนั้นอย่างนุ่มนวลในคำอ่าน แล้วเปลี่ยนไปอ่านเรื่องทัศนคติต่อเงินและความเสี่ยงของผู้ถามแทน",
    };
  }

  if (matchAny(THIRD_PARTY_PATTERNS, text)) {
    return {
      flag: "third_party",
      block: false,
      promptGuard:
        "คำถามนี้ต้องการข้อมูลระบุตัวบุคคลอื่น ห้ามเดาชื่อ รูปพรรณ สถานที่ หรือรายละเอียดที่ชี้ตัวคนได้เด็ดขาด ให้อ่านเฉพาะพลังงานของความสัมพันธ์และสิ่งที่ผู้ถามควรทำกับความรู้สึกของตัวเอง",
    };
  }

  return { flag: "none", block: false };
}

