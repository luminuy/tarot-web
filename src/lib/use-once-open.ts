"use client";

import { useRef } from "react";

/**
 * ✦ `useOnceOpen(isOpen)` — "ยังไม่เคยเปิด ก็ยังไม่ต้องมีตัวตน"
 * ---------------------------------------------------------------------------
 * คืน `true` ตั้งแต่วินาทีแรกที่ `isOpen` เป็นจริง แล้ว **ค้างเป็น `true` ตลอดไป**
 *
 * **ไว้ทำอะไร** — หน้าต่างซ้อน (modal) ทั้ง 7 บานของหน้าแรกถูกเรนเดอร์ทิ้งไว้
 * ตลอดเวลาโดยส่ง `isOpen={false}` เข้าไป · ตัวมันเองไม่วาดอะไรก็จริง แต่การที่มัน
 * **ถูก mount** ทำให้ `next/dynamic` สั่งโหลด chunk ของมันทันทีที่ hydrate เสร็จ
 * รวมถึงไลบรารี `motion` 40 KB (gzip) ที่หน้าต่างพวกนี้ใช้
 *
 * ผลคือผู้ใช้ที่แค่เปิดหน้าแรกมาดูแล้วปิดไป (ซึ่งเป็นคนส่วนใหญ่) ต้องจ่ายค่าดาวน์โหลด
 * ของหน้าต่างที่ไม่เคยเปิดครบทุกบาน · ห่อด้วยฮุกนี้แล้วจะโหลดตอนกดเปิดครั้งแรกเท่านั้น
 *
 * **ทำไมต้องค้างเป็น true ไม่ใช่ตามค่า `isOpen` ตรง ๆ**
 * ถ้าถอด component ออกทุกครั้งที่ปิด อนิเมชันขาออกจะไม่มีโอกาสได้เล่นเลย
 * (`Modal.tsx` คุมขาออกด้วย `<AnimatePresence>` ที่อยู่ **ข้างใน** ตัวมันเอง —
 * ถ้าตัวแม่ถอดมันทิ้งก่อน อนิเมชันก็ตายไปพร้อมกัน) · เปิดครั้งแรกแล้วปล่อยค้างไว้
 * จึงได้ทั้งสองอย่าง: ไม่โหลดของที่ไม่ใช้ และปิดแล้วยังค่อย ๆ จางหายเหมือนเดิม
 *
 * ref อ่านตอน render ได้โดยไม่ผิดกฎ ISSUE-008 เพราะค่าเริ่มต้นเป็นค่าคงที่ที่เหมือนกัน
 * ทั้งฝั่งเซิร์ฟเวอร์และเบราว์เซอร์ (`false`) ไม่ได้อ่านอะไรที่ขึ้นกับเบราว์เซอร์
 * และการพลิกเป็น `true` เกิดพร้อมกับ state ที่สั่งเปิดอยู่แล้ว จึงมี re-render รองรับเสมอ
 */
export function useOnceOpen(isOpen: boolean): boolean {
  const hasOpenedRef = useRef(false);
  if (isOpen) hasOpenedRef.current = true;
  return hasOpenedRef.current;
}
