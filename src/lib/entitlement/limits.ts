/**
 * ผู้เยี่ยมชมที่ยังไม่สมัคร: ทดลองฟรีได้กี่ครั้ง (ตลอดชีพ)
 *
 * ⚠️ **0 = ต้องสมัครสมาชิก/เข้าสู่ระบบก่อนถึงเปิดไพ่ได้** (คำสั่งเจ้าของโปรเจกต์ 2026-09-09)
 * เว็บยังฟรีเหมือนเดิมทุกอย่าง แค่ย้ายเส้นเริ่มต้นมาไว้ที่การสมัครสมาชิก
 * เนื้อหาที่ไม่ต้องล็อกอิน (สารานุกรมไพ่ 78 ใบ · คลังผัง · บทความ · ไพ่ประจำวันฝั่งเบราว์เซอร์)
 * ไม่ได้รับผลจากค่านี้เลย — ค่านี้คุมเฉพาะ "การเปิดไพ่ที่เรียก AI" เท่านั้น
 *
 * กลับไปเปิดให้ทดลองฟรีโดยไม่สมัครได้ด้วยการตั้งค่านี้กลับเป็น 1 — ถ้อยคำ เหตุผลที่ส่งให้ UI
 * และด่าน QA อ่านค่าจากที่นี่ที่เดียวทั้งหมด (ดู `REQUIRE_SIGNUP_TO_READ` ด้านล่าง)
 */
export const GUEST_LIMIT = 0;

/**
 * เว็บกำลังบังคับ "สมัครก่อนเล่น" อยู่หรือไม่ — อนุมานจาก `GUEST_LIMIT` ห้ามตั้งค่าซ้ำเอง
 * ใช้เลือกถ้อยคำและเหตุผลของกำแพงสิทธิ์ให้ตรงความจริงเสมอ แม้วันหนึ่งจะเปิดสิทธิ์ทดลองกลับมา
 */
export const REQUIRE_SIGNUP_TO_READ = GUEST_LIMIT <= 0;

/**
 * เหตุผลที่ผู้เยี่ยมชมถูกกั้น — `signup_required` (ยังไม่เคยได้เล่นเลย ต้องสมัครก่อน)
 * ต่างจาก `guest_used` (เคยได้ทดลองฟรีแล้วและใช้ครบ) ซึ่งเป็นถ้อยคำคนละเรื่องกันสิ้นเชิง
 * บอกผู้ใช้ผิดข้อไหนก็ทำให้เขางงว่า "ไม่เคยเล่นแล้วใช้สิทธิ์หมดตอนไหน"
 */
export const GUEST_BLOCK_REASON = REQUIRE_SIGNUP_TO_READ ? "signup_required" : "guest_used";

