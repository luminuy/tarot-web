/** จำนวนครั้งที่ยอมสุ่มใหม่ก่อนตกไปใช้ทางถอย (โอกาสได้ derangement ของ 4 ช่อง ≈ 37.5% ต่อครั้ง) */
const MAX_ATTEMPTS = 24;

export function drawContentOrder(size: number, prev: readonly number[]): number[] {
  if (size < 2) return Array.from({ length: size }, (_, i) => i);

  const previous = prev.length === size ? prev : Array.from({ length: size }, (_, i) => i);

  for (let attempt = 0; attempt < MAX_ATTEMPTS; attempt++) {
    const next = Array.from({ length: size }, (_, i) => i);
    for (let i = next.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [next[i], next[j]] = [next[j], next[i]];
    }
    if (next.every((value, index) => value !== previous[index])) return next;
  }

  // ทางถอยที่ยังการันตีว่าไม่ซ้ำช่องเดิม — เลื่อนลำดับเดิมไปหนึ่งช่อง
  return previous.map((_, index) => previous[(index + 1) % size]);
}
