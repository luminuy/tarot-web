/**
 * 💬 ตัวจัดรูปแบบข้อความแชทของแม่หมอ — โมดูลบริสุทธิ์ ไม่พึ่ง React
 * ===========================================================================
 *
 * แยกออกมาจาก `FollowUpChat.tsx` เพื่อให้ **ด่าน CI ยิงทดสอบด้วยเคสจริงได้**
 * (INC-0212 — กฎที่ไม่มีเครื่องตรวจ คือกฎที่จะถูกละเมิดอีกแน่นอน)
 *
 * ⚠️ ห้ามย้าย regex พวกนี้กลับไปเขียนในคอมโพเนนต์ ด่านจะตรวจไม่ได้ทันที
 */

/**
 * แปลงข้อความดิบจากโมเดลให้เป็น "ย่อหน้า" ที่คอมโพเนนต์เอาไปเรนเดอร์ทีละใบ
 *
 * 1. หัวข้อย่อยที่เขียนด้วย `-` / `–` / `—` / `•` / `✦` ➔ `• **หัวข้อ:**`
 * 2. ลำดับขั้นตอน `1.` `2.` `3.` ➔ ขึ้นย่อหน้าใหม่ทีละข้อ
 */
export function splitChatParagraphs(text: string): string[] {
  return (
    text
      /*
       * 🚨 ยัติภังค์ต้องมี "ช่องว่างขนาบสองข้าง" เท่านั้นถึงจะนับเป็นหัวข้อย่อย (INC-0212)
       * ของเดิมเขียน `[✦•\-]\s*` ซึ่ง `\s*` ยอมให้ศูนย์ช่องว่าง ขีดกลาง "กลางคำ"
       * จึงถูกนับเป็นหัวข้อย่อยไปด้วย — คำว่า "(De-load Routine):" ถูกผ่าครึ่ง
       * กลายเป็นย่อหน้า "1. **ทำกิจวัตรลดภาระ (De" กับ "• **load Routine):**** จด..."
       * ผู้ใช้เห็นเป็นคำขาดหายกลางคัน + `**` โผล่ดิบ ๆ (ผู้ทดสอบถ่ายภาพมายืนยัน)
       * คำแบบนี้เจอได้เรื่อย ๆ: De-load · self-care · e-mail · work-life · Co-founder
       */
      .replace(/(^|[\n\s])[-–—][ \t]+([^\n:]+):/g, "$1\n\n• **$2:**")
      /*
       * `•` กับ `✦` เป็นสัญลักษณ์หัวข้อแท้ ไม่มีทางอยู่กลางคำ จึงไม่ต้องบังคับช่องว่าง
       * แต่ต้องมี `(?![ \t]*\*\*)` กันไม่ให้ไปห่อซ้ำของที่บรรทัดบนแปลงไปแล้ว (INC-0212)
       * ถ้าไม่กัน `• **หัวข้อ:**` จะถูกห่ออีกชั้นเป็น `• ****หัวข้อ:****`
       * แล้ว regex ของการ์ดไพ่จะจับ `\*\*(.*?)\*\*` ได้เป็นสตริงว่าง — หัวข้อสีทองหายทั้งอัน
       */
      .replace(/[✦•](?![ \t]*\*\*)[ \t]*([^\n:]+):/g, "\n\n• **$1:**")
      .replace(/([^\n])\s+(\d+\.\s+\*\*)/g, "$1\n\n$2")
      .replace(/([^\n])\s+(\d+\.\s+[ก-๙a-zA-Z])/g, "$1\n\n$2")
      .trim()
      .split(/\n\s*\n+/)
      .map((p) => p.trim())
      .filter(Boolean)
  );
}

/**
 * 🧹 กวาด `**` ที่เหลือค้างทิ้ง (INC-0212)
 *
 * ตัวเรนเดอร์จับเฉพาะดาวที่ "ปิดครบคู่" ตัวที่เหลือคือดาวที่ไม่มีคู่ ซึ่งเกิดได้เสมอ
 * เมื่อโมเดลพิมพ์ดาวไม่ครบ หรือย่อหน้าถูกตัดกลางคัน
 * ถ้าปล่อยไว้ ผู้ใช้จะเห็น `**` โผล่กลางคำทำนายแบบดิบ ๆ
 * ไม่มีกรณีไหนที่ดาวคู่เป็นเนื้อหาจริงของคำทำนาย จึงตัดทิ้งได้ปลอดภัย
 */
export function stripStrayBoldMarkers(part: string): string {
  return part.replace(/\*\*/g, "");
}
