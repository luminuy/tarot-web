/**
 * 🌐 โฮสต์หลักของเว็บ และโฮสต์รองที่ต้องเด้งกลับมาหามัน (Canonical Host Policy)
 * ===========================================================================
 *
 * ## ทำไมต้องมีไฟล์นี้ (บทเรียน INC-0203)
 *
 * เดิมกฎ "www ➔ โดเมนหลัก" เขียนไว้ที่เดียวคือ `next.config.ts` → `redirects()`
 * ซึ่ง **ทำงานเฉพาะคำขอที่วิ่งถึง Worker** ตอนที่เขียนกฎนั้น Next เรนเดอร์ทุกหน้า
 * กฎจึงครอบคลุมทั้งเว็บจริง ๆ
 *
 * พอย้ายหน้าเนื้อหาไป Astro (คลื่น 1–4) หน้าเหล่านั้นกลายเป็น **ไฟล์ static ที่
 * Cloudflare ตอบเองที่ขอบ โดยไม่ปลุก Worker เลย** — กฎใน `next.config.ts`
 * จึงไม่เคยถูกเรียกสำหรับหน้าเหล่านั้นอีกต่อไป ผลคือ `https://www.seertarot.net/cards`
 * ตอบ 200 พร้อมเนื้อหาเต็ม (เว็บซ้ำสองโฮสต์) ทั้งที่กฎ 301 ยังอยู่ในโค้ดครบถ้วน
 * — ไม่มีอะไรพัง ไม่มีด่านไหนฟ้อง เห็นได้ทางเดียวคือยิง curl ใส่โฮสต์ www
 *
 * ## กติกาที่ตามมา — กฎระดับโฮสต์ต้องมี **สองชั้นเสมอ**
 *
 *   ชั้นขอบ (ของจริง)  `scripts/cloudflare-canonical-host.ts` ➔ Single Redirect ของ Cloudflare
 *                      เด้งก่อนถึงชั้น assets จึงครอบคลุม **ทุกเส้นทาง** รวมหน้า Astro
 *   ชั้น Worker (สำรอง) `next.config.ts` → `redirects()` ครอบเฉพาะเส้นทางที่ถึง Worker
 *
 * ทั้งสองชั้นอ่านรายชื่อโฮสต์จากไฟล์นี้ไฟล์เดียว และด่าน
 * `scripts/qa/test-canonical-host.ts` บังคับให้ทั้งสองชั้นยังพูดตรงกันอยู่เสมอ
 *
 * ⚠️ เพิ่มโฮสต์ใหม่ (เช่น โดเมนเก่าที่ซื้อไว้) ➔ เติมที่ `ALTERNATE_HOSTS` ที่เดียวพอ
 *    แล้วรัน `npm run cf:canonical-host` เพื่อดันกฎขึ้นขอบ
 */
import { SITE_DOMAIN, SITE_ORIGIN } from "./site-constants";

/** โฮสต์เดียวที่เนื้อหาทั้งเว็บควรถูกจัดทำดัชนีภายใต้ชื่อนี้ */
export const CANONICAL_HOST = SITE_DOMAIN;

/** origin เต็มของโฮสต์หลัก — ปลายทางของการเด้งทุกเส้น */
export const CANONICAL_ORIGIN = SITE_ORIGIN;

/**
 * โฮสต์อื่นที่ชี้มาที่ Worker/โซนเดียวกัน และต้องเด้ง 301 กลับหาโฮสต์หลัก
 *
 * ทุกชื่อในรายการนี้ต้อง **ชี้มาที่เว็บนี้จริง** (มี DNS record ในโซน) ไม่งั้นกฎที่ดันขึ้นขอบ
 * จะเป็นกฎที่ไม่มีวันถูกเรียก — เปลืองช่องกฎบนแพ็กเกจ Free ที่มีจำกัด
 */
export const ALTERNATE_HOSTS = [`www.${SITE_DOMAIN}`] as const;

/** ปลายทางของโฮสต์รองแต่ละตัว (ใช้ร่วมกันทั้งชั้นขอบและชั้น Worker) */
export function canonicalRedirectTarget(pathname: string): string {
  return `${CANONICAL_ORIGIN}${pathname}`;
}
