"use client";

import { AUTH_HINT_COOKIE_NAME } from "@/lib/auth/cookie-names";

/**
 * 🪶 "เครื่องนี้มีเซสชันอยู่ไหม" — ตอบได้โดยไม่ต้องยิงเซิร์ฟเวอร์
 * ---------------------------------------------------------------------------
 * ทุกหน้าของเว็บมีแถบโปรไฟล์ · การ์ดสิทธิ์ · ประวัติการเปิดไพ่ ซึ่งล้วนต้องรู้ว่า
 * "ใครกำลังใช้อยู่" เดิมจึงยิง `/api/auth/me` ทุกครั้งที่โหลดหน้า แม้ผู้ชมจะไม่เคย
 * ล็อกอินเลยสักครั้ง — ซึ่งคือผู้ชมเกือบทั้งหมดที่มาจาก Google
 *
 * ตัวชี้ขาดคือ **คุกกี้ใบ้ `tarot_has_session`** ที่เซิร์ฟเวอร์ตั้งให้ตอนล็อกอินสำเร็จ
 * (ไม่ใช่ httpOnly หน้าเว็บจึงอ่านเองได้) และมีอายุเท่าคุกกี้เซสชันเป๊ะ ๆ (30 วัน)
 * เพราะ `hintCookieOptions()` ยืมค่าจาก `authCookieOptions()` มาทั้งชุด
 * ➔ **ไม่มีคุกกี้ใบ้ = ไม่มีเซสชัน = ไม่ต้องถามเซิร์ฟเวอร์เลย**
 *
 * 📌 ของเดิมยังต้องถาม 1 ครั้งต่อแท็บ เพราะเผื่อบัญชีที่ล็อกอินไว้ "ก่อน" ระบบคุกกี้ใบ้
 * (PR #356 · 2026-09-08) เจ้าของโปรเจกต์ตัดสินใจเมื่อ 2026-09-09 ว่ายอมแลก —
 * ผู้ใช้กลุ่มนั้นจะต้องล็อกอินใหม่หนึ่งครั้ง เพื่อให้ผู้ชมจาก Google ทุกคนไม่ต้องยิงเส้นนี้อีกเลย
 *
 * ⚠️ คุกกี้ใบ้เป็นแค่ตัวช่วย "ประหยัดคำขอ" เท่านั้น **ห้ามใช้ตัดสินสิทธิ์ใด ๆ**
 * การบังคับสิทธิ์ทั้งหมดยังอยู่ฝั่งเซิร์ฟเวอร์ที่ตรวจคุกกี้เซสชัน httpOnly ตัวจริงเสมอ
 * (ผู้ใช้แก้คุกกี้ใบ้เองได้ ผลที่ได้อย่างมากคือหน้าเว็บยิงถามเซิร์ฟเวอร์เพิ่มอีกครั้ง)
 */

/** เครื่องนี้เคยล็อกอินและเซสชันยังอยู่หรือไม่ (ดูจากคุกกี้ใบ้) */
export function hasSessionHint(): boolean {
  if (typeof document === "undefined") return false;
  return document.cookie.split("; ").some((c) => c.startsWith(`${AUTH_HINT_COOKIE_NAME}=1`));
}

/**
 * `true` เมื่อ "รู้แน่แล้วว่ายังไม่ล็อกอิน" จึงข้ามการยิงถามเซิร์ฟเวอร์ได้ทั้งหมด
 * — ระหว่าง SSR ตอบ `false` ไว้ก่อนเสมอ เพราะยังอ่านคุกกี้ไม่ได้
 */
export function isKnownAnonymous(): boolean {
  if (typeof window === "undefined") return false;
  return !hasSessionHint();
}
