/**
 * 🧘 Mindful Micro-Ritual Generator
 * -----------------------------------
 * สร้างกิจกรรมฝึกสติ 60 วินาทีตามผลเคมีธาตุของไพ่ เพื่อฟื้นฟูสมดุลชีวิต:
 * - ขาดธาตุน้ำ ➔ วารีบำบัดใจ (Heart Hydration)
 * - ขาดธาตุไฟ ➔ จุดประกายไฟแห่งเจตจำนง (Ignite the Spark)
 * - ขาดธาตุดิน ➔ หยั่งรากลงดิน (Grounding Reset)
 * - ขาดธาตุลม ➔ สลายความคิดฟุ้งซ่าน (Box Breathing Reset)
 * - ธาตุสมดุล ➔ วงกลมแห่งความซาบซึ้ง (Circle of Gratitude)
 */

export interface MindfulRitual {
  targetElement: string;
  titleTh: string;
  durationText: string;
  actionText: string;
  adviceString: string;
}

/**
 * สร้างคำแนะนำฝึกสติตามธาตุที่ขาดหายไปในผัง
 */
export function generateMindfulMicroRitual(
  lackingElements: string[] = [],
  dominantElement: string | null = null
): MindfulRitual {
  // 1. ถ้าขาดธาตุน้ำ (ละเลยความรู้สึก/จิตใจแห้งแล้ง)
  if (lackingElements.includes("น้ำ")) {
    return {
      targetElement: "น้ำ",
      titleTh: "วารีบำบัดใจ (Heart Hydration)",
      durationText: "60 วินาที",
      actionText:
        "รินน้ำเปล่า 1 แก้ว หลับตาลงช้า ๆ วางมือขวาบนหน้าอก ดื่มน้ำทีละจิบอย่างมีสติ แล้วบอกตัวเองในใจว่า 'ฉันอนุญาตให้ตัวเองได้รู้สึก พักผ่อน และใจดีกับตัวเองในวันนี้'",
      adviceString:
        "🧘 กิจกรรมฝึกสติ 1 นาที (เติมธาตุน้ำ): วางมือขวาบนหน้าอก ดื่มน้ำ 1 แก้วอย่างมีสติ แล้วบอกตัวเองว่า 'ฉันอนุญาตให้ตัวเองได้รู้สึก พักผ่อน และใจดีกับตัวเองในวันนี้'",
    };
  }

  // 2. ถ้าขาดธาตุไฟ (ขาดพลังใจ/หมดไฟ/ลังเลไม่เริ่ม)
  if (lackingElements.includes("ไฟ")) {
    return {
      targetElement: "ไฟ",
      titleTh: "จุดประกายไฟแห่งเจตจำนง (Ignite the Spark)",
      durationText: "60 วินาที",
      actionText:
        "ยืนขึ้น ยืดตัวตรง สูดหายใจเข้าลึก ๆ ให้เต็มปอด ก้าวเท้าขวาไปข้างหน้า 1 ก้าวอย่างมั่นคง แล้วกล่าวเป้าหมาย 1 อย่างที่คุณจะทำให้สำเร็จในวันนี้ด้วยความมั่นใจ",
      adviceString:
        "🧘 กิจกรรมฝึกสติ 1 นาที (เติมธาตุไฟ): ยืนยืดตัวตรง สูดหายใจลึก ก้าวไปข้างหน้า 1 ก้าว แล้วเอ่ยเป้าหมาย 1 อย่างที่คุณจะลงมือทำในวันนี้อย่างมั่นคง",
    };
  }

  // 3. ถ้าขาดธาตุดิน (คิดเยอะแต่ไม่ทำ/ฟุ้งซ่านไร้รากฐาน)
  if (lackingElements.includes("ดิน")) {
    return {
      targetElement: "ดิน",
      titleTh: "หยั่งรากลงดิน (Grounding Reset)",
      durationText: "60 วินาที",
      actionText:
        "วางฝ่าเท้าทั้งสองข้างแนบสนิทกับพื้น สัมผัสความหนักแน่นของผืนดิน เขียนงานหรือเป้าหมายที่เล็กที่สุด 1 อย่างลงกระดาษ แล้วลงมือทำให้เสร็จใน 10 นาที",
      adviceString:
        "🧘 กิจกรรมฝึกสติ 1 นาที (เติมธาตุดิน): วางเท้าเปล่าแนบพื้น สัมผัสความหนักแน่นของผืนดิน แล้วเลือกทำสิ่งเล็กๆ 1 อย่างให้เสร็จจริงใน 10 นาทีนี้",
    };
  }

  // 4. ถ้าขาดธาตุลม (คิดไม่ตก/ขาดการสื่อสาร/อึดอัด)
  if (lackingElements.includes("ลม")) {
    return {
      targetElement: "ลม",
      titleTh: "สลายความคิดฟุ้งซ่าน (Box Breathing Reset)",
      durationText: "60 วินาที",
      actionText:
        "หลับตาลง หายใจเข้า 4 วินาที กลั้นหายใจ 4 วินาที แล้วหายใจออกช้า ๆ 6 วินาที ทำซ้ำ 3 รอบ เพื่อระบายความอึดอัดและเปิดพื้นที่ว่างให้สติปัญญา",
      adviceString:
        "🧘 กิจกรรมฝึกสติ 1 นาที (เติมธาตุลม): หลับตาลง ฝึกหายใจเข้า 4 วิ กลั้น 4 วิ ผ่อนลมหายใจออก 6 วิ ทำซ้ำ 3 รอบ เพื่อเคลียร์สมองให้ปลอดโปร่ง",
    };
  }

  // 5. ถ้าธาตุสมดุลครบถ้วน
  return {
    targetElement: dominantElement || "สมดุล",
    titleTh: "วงกลมแห่งความซาบซึ้ง (Circle of Gratitude)",
    durationText: "60 วินาที",
    actionText:
      "หลับตาลง 1 นาที นึกถึงเรื่องดี ๆ หรือความพยายามของตนเอง 1 เรื่องในวันนี้ แล้วส่งรอยยิ้มขอบคุณให้กับตัวเองที่เข้มแข็งและเติบโตมาจนถึงตอนนี้",
    adviceString:
      "🧘 กิจกรรมฝึกสติ 1 นาที (น้อมรับความสมดุล): หลับตา 1 นาที นึกถึงความพยายามของตัวเอง 1 เรื่อง แล้วขอบคุณหัวใจตัวเองที่เข้มแข็งเสมอมา",
  };
}
