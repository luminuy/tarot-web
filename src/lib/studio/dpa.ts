export function isStudioEnabled(): boolean {
  return process.env.READER_STUDIO_ENABLED === "1";
}

/**
 * ร่างด้วย AI ใช้ได้ต่อเมื่อเจ้าของยืนยันว่าคีย์ Gemini อยู่บน **บริการแบบเสียเงิน (Paid Services)** แล้ว
 * ข้อกำหนด Gemini API: บริการฟรี = Google นำ prompt/คำตอบไปพัฒนาผลิตภัณฑ์และอาจให้คนอ่าน ·
 * บริการเสียเงิน = ไม่นำไปพัฒนา (เก็บชั่วคราวเพื่อตรวจการใช้ผิดนโยบายเท่านั้น)
 * ข้อตกลง DPA ข้อ 7 สัญญาว่า "ไม่ใช้ฝึกโมเดล" ➔ ยังไม่ยืนยัน = ร่างออฟไลน์จากโน้ตของหมอ (ไม่ส่งอะไรให้ AI เลย)
 * ตั้ง `STUDIO_AI_PAID_TIER=1` หลังเปิด billing ของโปรเจกต์ Google AI Studio ที่ออกคีย์นั้นแล้วเท่านั้น
 */
export function isStudioAiAllowed(): boolean {
  return process.env.STUDIO_AI_PAID_TIER === "1";
}

export function hasAcceptedDpa(version: string | null | undefined): boolean {
  return version === STUDIO_DPA_VERSION;
}
