/** เลขข้อที่ผู้เขียนพิมพ์นำหน้าไว้ เช่น "1. " · "2) " · "10." */
const LEADING_NUMBER = /^\s*(\d{1,3})[.)]\s+/;

export interface TocLabel {
  /** ตัวเลขที่จะแสดงหน้าหัวข้อ (ยังไม่มีจุด) */
  marker: string;
  /** ชื่อหัวข้อที่ตัดเลขนำหน้าออกแล้ว */
  label: string;
}

export function splitTocNumber(title: string, fallbackIndex: number): TocLabel {
  const matched = LEADING_NUMBER.exec(title);
  if (!matched) return { marker: String(fallbackIndex), label: title.trim() };
  return { marker: matched[1], label: title.slice(matched[0].length).trim() };
}
