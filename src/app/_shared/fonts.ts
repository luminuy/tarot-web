export const notoSerifThai = localFont({
  src: [
    { path: "./fonts/noto-serif-thai-400.woff2", weight: "400", style: "normal" },
    { path: "./fonts/noto-serif-thai-700.woff2", weight: "700", style: "normal" },
  ],
  display: "swap",
  variable: "--font-noto-serif-thai",
  /*
   * Next คำนวณ `size-adjust` + `ascent/descent-override` ของฟอนต์สำรองจากเมตริก
   * ของไฟล์จริงให้เอง ตัวอักษรจึงกินที่เท่ากันทั้งก่อนและหลังสลับ = ไม่เกิด layout shift
   *
   * ⚠️ **ต้องเป็น "Arial" ห้ามใช้ "Times New Roman"** — วัดจริงแล้วพังจริง (2026-09-14)
   * ค่านี้ไม่ได้เป็นแค่ชื่อสำหรับคำนวณ แต่ Next เอาไปใส่ใน `src: local("...")` ของ
   * `@font-face` ตัวสำรองด้วย · ถ้าเครื่องผู้ใช้ไม่มีฟอนต์ชื่อนั้น ตัวสำรองจะโหลดไม่สำเร็จ
   * **ค่าชดเชยเมตริกทั้งชุดจึงไม่ถูกใช้เลย** แล้วข้อความไปตกที่ฟอนต์ระบบแบบดิบ ๆ
   *
   * ตอนตั้งเป็น "Times New Roman" ครั้งแรก: `document.fonts` รายงานสถานะ **error**
   * และ CLS เด้งจาก 0.004 เป็น **0.128** โดยตัวที่ขยับคือหัวเรื่องกลางหน้าแรก
   * ซึ่งดันแผงเลือกหัวข้อลงไป 29px ตอนฟอนต์มาถึง
   *
   * "Arial" ปลอดภัยกว่ามากเพราะระบบปฏิบัติการเกือบทุกตัวมีหรือ alias ไว้ให้
   * (Android ➔ Roboto · Linux ➔ Liberation Sans) ซึ่งเป็นกลุ่มผู้ใช้หลักของเว็บนี้
   * ส่วนที่ฟอนต์จริงเป็น serif แต่ตัวสำรองเป็น sans ไม่มีผลกับเลย์เอาต์
   * เพราะสิ่งที่ Next ชดเชยคือ "ขนาดและความสูงบรรทัด" ไม่ใช่รูปทรงตัวอักษร
   *
   * ⚠️ ห้ามตั้งเป็น false — CLS จะกลับมาทันทีตอนฟอนต์สลับ
   * ⚠️ ห้ามใส่ `fallback: [...]` เป็นชื่อฟอนต์ที่ผู้ใช้ไม่มีติดเครื่อง (เช่น "Noto Serif Thai")
   *    มันจะถูกวางต่อท้ายตัวสำรองที่ชดเชยเมตริกแล้ว กลายเป็นทางหนีที่ไม่มีการชดเชย
   *
   * 📌 แม้จะชดเชยเมตริกแล้ว การสลับฟอนต์ก็ยัง **เปลี่ยนจุดตัดบรรทัด** ของข้อความไทยยาว ๆ ได้
   *    ซึ่ง `size-adjust` แก้ไม่ได้ — นั่นคือเหตุผลที่ฟอนต์ทุกตัวต้อง `preload` (ดูหัวข้อด้านบน)
   */
  adjustFontFallback: "Arial",
});

