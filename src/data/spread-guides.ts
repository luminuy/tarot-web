export interface SpreadGuideExample {
  cards: { position: string; cardId: string; cardName: string; text: string }[];
  summary: string;
}

/**
 * ภาพประกอบของแถว (แผงครีมฝั่งตรงข้ามข้อความ · `aria-hidden`) — ไพ่เลือกตามความหมายดั้งเดิมของไพ่
 * ไม่ใช่ผลเปิดไพ่ของใคร (เหมือน `Ui2FeatureRows` หน้าอื่น) · ข้อความจริงต้องอยู่ฝั่งตัวหนังสือครบเสมอ
 */
export interface SpreadGuideMock {
  tint: "gold" | "teal" | "violet";
  /** ไพ่ 3 ใบกางเป็นพัด (ใบกลางใหญ่สุด) */
  fan?: readonly [string, string, string];
  /** ช่องพิมพ์คำถามจำลอง */
  input?: { title: string; text: string };
  panel?: { label: string; items: string[] };
}

/** หนึ่งแถวของคู่มือ — แถวสลับซ้ายขวาแบบหน้าแรก (`Ui2FeatureRows`) */
export interface SpreadGuideBlock {
  kicker: string;
  heading: string;
  paragraphs?: string[];
  /** รายการหัวข้อสั้น + คำอธิบาย (`href` = ลิงก์ภายในของหัวข้อนั้น) */
  points?: { term: string; text: string; href?: string }[];
  example?: SpreadGuideExample;
  mock: SpreadGuideMock;
}

export interface SpreadGuide {
  title: string;
  lede: string;
  blocks: SpreadGuideBlock[];
  faqs: { question: string; answer: string }[];
}

/** ไพ่ในตัวอย่างการอ่าน ➔ แผงภาพประกอบของแถวนั้น (ไพ่ชุดเดียวกับที่ข้อความเล่า) */
function exampleMock(tint: SpreadGuideMock["tint"], example: SpreadGuideExample): SpreadGuideMock {
  const [a, b, c] = example.cards;
  return {
    tint,
    fan: [a.cardId, b.cardId, c.cardId],
    panel: { label: "ไพ่ที่ออก", items: example.cards.map((x) => `${x.position} ${x.cardName}`) },
  };
}

