export function getAllTopicSlugs(): string[] {
  return Object.keys(SPREAD_TOPICS);
}

export function getSpreadTopic(slug: string): SpreadTopic | undefined {
  return SPREAD_TOPICS[slug];
}

export function getSpreadsForTopic(topic: SpreadTopic): Spread[] {
  return topic.spreadIds
    .map((id) => SPREADS.find((s) => s.id === id))
    .filter((s): s is Spread => s !== undefined);
}
