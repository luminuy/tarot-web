/**
 * เลือกตัวอย่างคำอ่านมาตรฐานที่เหมาะสมที่สุดตาม (หมวดคำถาม × ขนาดผังไพ่ × โหมดใช่/ไม่ใช่)
 * ป้องกันการ Throw เสมอ (Graceful Fallback 100%)
 */
export function pickExemplar(
  category: Category | string,
  cardCount: number,
  yesNoMode?: boolean,
): ExemplarItem {
  // 1. ตรวจ Yes/No ก่อน หากเปิดโหมดใช่/ไม่ใช่
  if (yesNoMode) {
    const yn = EXEMPLARS.find((e) => e.yesNoMode);
    if (yn) return yn;
  }

  // 2. หาตัวที่ตรงทั้ง category และ cardCount เป๊ะ ๆ
  const exact = EXEMPLARS.find(
    (e) => !e.yesNoMode && e.category === category && e.cardCount === cardCount,
  );
  if (exact) return exact;

  // 3. หาตัวที่ตรง category แต่ cardCount ใกล้เคียงที่สุด
  const sameCat = EXEMPLARS.filter((e) => !e.yesNoMode && e.category === category);
  if (sameCat.length > 0) {
    sameCat.sort((a, b) => Math.abs(a.cardCount - cardCount) - Math.abs(b.cardCount - cardCount));
    return sameCat[0];
  }

  // 4. หาตัวที่มี cardCount เท่ากันหรือใกล้เคียงที่สุดจากหมวดใดก็ได้
  const candidates = EXEMPLARS.filter((e) => !e.yesNoMode);
  candidates.sort((a, b) => Math.abs(a.cardCount - cardCount) - Math.abs(b.cardCount - cardCount));
  return candidates[0] || EXEMPLARS[0];
}

